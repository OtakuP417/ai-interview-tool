-- 访谈过程的「规则未执行」事件日志（L4 可观测性）
--
-- 背景：扫 6 份归档 / 169 轮对话后发现，凡「要求模型停下或退回」的提示词规则
--       （开场先确认主题、连续短答换访谈形态、追失效边界）在真实访谈里
--       执行率是 0；而「继续追问」类规则执行率 67~100%。
--       执行率取决于「规则方向」和「有无代码兜底」，不取决于提示词写得多好。
--       于是把判断从提示词搬到代码：命中条件就往本轮注入一条即时指令。
--
-- 但「注入有没有让模型照做」此前只能靠人读 40 多轮对话判断（那次诊断就是
-- 人工做的，不可持续）。本列记录前端采集到的事件，只含类别与轮次，
-- 不含任何访谈内容：
--
--   inject_opener    开场未复述主题，靠注入纠正
--   inject_switch    连续短答，靠注入换访谈形态
--   inject_release   三种换法用尽，靠注入止损
--   inject_number    主题里的数字没问来路，靠注入催问
--   inject_boundary  做法讲完没问失效边界，靠注入催问
--   gate_fixed       回复不合格（多问/半句/空），被闸门拦下并重写成功
--   gate_unfixed     同上但重写仍不合格，保留原文
--
-- 用途：横向统计「哪条规则靠自己生效、哪条靠兜底」，并验证注入是否真的有效 ——
--       若某类 inject_* 长期为 0，说明那条规则模型已经自己做到了，注入可以撤掉。

ALTER TABLE interview_reports
  ADD COLUMN IF NOT EXISTS gate_log jsonb;

COMMENT ON COLUMN interview_reports.gate_log IS '访谈过程事件日志（规则注入与回复闸门命中，只含类别与轮次，不含访谈内容）';
